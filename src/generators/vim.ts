import { ANSI_NAMES, ansi, type ColorName, color, type Palette, syntax } from "../palette.ts";
import type { Target } from "./types.ts";

export const vim: Target = {
  id: "vim",
  name: "Vim / Neovim",
  files(p: Palette) {
    const c = (n: ColorName) => color(p, n);
    const s = (r: Parameters<typeof syntax>[1]) => syntax(p, r);
    const hi = (group: string, fg?: string, bg?: string, attr?: string) =>
      `hi ${group} guifg=${fg ?? "NONE"} guibg=${bg ?? "NONE"} gui=${attr ?? "NONE"} cterm=${attr ?? "NONE"}`;
    const lines = [
      '" Bigface — https://github.com/gjuoun/bigface-theme',
      '" Install: copy to ~/.vim/colors/bigface.vim (or ~/.config/nvim/colors/), then `:colorscheme bigface`.',
      "hi clear",
      'if exists("syntax_on") | syntax reset | endif',
      "set background=dark",
      "if has('termguicolors') | set termguicolors | endif",
      'let g:colors_name = "bigface"',
      "",
      `let g:terminal_ansi_colors = [${ANSI_NAMES.map((n) => `'${ansi(p, n)}'`).join(", ")}]`,
      "",
      hi("Normal", c("fg"), c("bg")),
      hi("NonText", c("border")),
      hi("EndOfBuffer", c("bg")),
      hi("Cursor", c("bg"), c("caret")),
      hi("CursorLine", undefined, c("cursorLine")),
      hi("CursorLineNr", c("fg"), c("cursorLine")),
      hi("LineNr", c("fgDim"), c("bg")),
      hi("SignColumn", undefined, c("bg")),
      hi("ColorColumn", undefined, c("borderMuted")),
      hi("VertSplit", c("borderMuted"), c("bg")),
      hi("WinSeparator", c("borderMuted"), c("bg")),
      hi("Visual", undefined, c("selection")),
      hi("Search", c("fg"), c("selection")),
      hi("IncSearch", c("bg"), c("burntOrange")),
      hi("MatchParen", c("fg"), c("braceMatch")),
      hi("Pmenu", c("fg"), c("cursorLine")),
      hi("PmenuSel", c("fg"), c("braceMatch")),
      hi("StatusLine", c("comment"), c("borderMuted")),
      hi("StatusLineNC", c("fgDim"), c("borderMuted")),
      hi("TabLine", c("fgDim"), c("borderMuted")),
      hi("TabLineSel", c("fg"), c("bg")),
      hi("TabLineFill", undefined, c("borderMuted")),
      hi("Folded", c("comment"), c("cursorLine")),
      hi("ErrorMsg", c("burntOrange"), c("bg"), "bold"),
      hi("WarningMsg", c("brightYellow")),
      hi("Directory", c("blue")),
      hi("Title", c("lime"), undefined, "bold"),
      "",
      hi("Comment", s("comment"), undefined, "italic"),
      hi("Constant", s("constant")),
      hi("String", s("string")),
      hi("Character", s("string")),
      hi("Number", s("number")),
      hi("Boolean", s("constant")),
      hi("Float", s("number")),
      hi("Identifier", s("variable")),
      hi("Function", s("function")),
      hi("Statement", s("keyword")),
      hi("Conditional", s("keyword")),
      hi("Repeat", s("keyword")),
      hi("Keyword", s("keyword")),
      hi("Operator", s("operator")),
      hi("PreProc", s("keyword")),
      hi("Type", s("type")),
      hi("StorageClass", s("keyword")),
      hi("Special", s("tag")),
      hi("Delimiter", s("punctuation")),
      hi("Tag", s("tag")),
      hi("Underlined", c("blue"), undefined, "underline"),
      hi("Error", c("burntOrange")),
      hi("Todo", c("burntOrange"), undefined, "bold"),
      hi("DiffAdd", c("green"), c("cursorLine")),
      hi("DiffDelete", c("burntOrange"), c("cursorLine")),
      hi("DiffChange", c("lightBlue"), c("cursorLine")),
      hi("DiffText", c("fg"), c("braceMatch")),
      "",
    ];
    return { "colors/bigface.vim": lines.join("\n") };
  },
};
