#!/bin/sh
# Bigface installer — https://github.com/gjuoun/bigface-theme
#
#   curl -fsSL https://gjuoun.github.io/bigface-theme/install.sh | sh -s -- ghostty tmux
#   curl -fsSL https://gjuoun.github.io/bigface-theme/install.sh | sh -s -- all          # every drop-in app it detects
#   curl -fsSL https://gjuoun.github.io/bigface-theme/install.sh | sh -s -- --list
#   curl -fsSL https://gjuoun.github.io/bigface-theme/install.sh | sh -s -- --dry-run all
#
# It only writes Bigface's own files (never edits your config) and prints the one line you still
# need to add. Read it first: it is this file.
#
# Environment: BIGFACE_BASE (site URL), BIGFACE_DRY_RUN=1, BIGFACE_VAULT (Obsidian vault path).
# Generated by src/installer.ts — do not edit by hand.
set -eu

BASE="${BIGFACE_BASE:-https://gjuoun.github.io/bigface-theme}"
DRY="${BIGFACE_DRY_RUN:-}"
CFG="${XDG_CONFIG_HOME:-$HOME/.config}"
IDS="pi ghostty herdr vscode zed jetbrains zellij starship tmux vim xcode micro obsidian slack raycast"
ALL="pi ghostty vscode zed zellij tmux vim xcode micro"

usage() {
  echo "usage: sh install.sh [--dry-run] [--list] <app>... | all"
}

list() {
  echo "Bigface apps:"
  printf '  %-10s %s\n' 'pi' 'installs the theme file'
  printf '  %-10s %s\n' 'ghostty' 'installs the theme file'
  printf '  %-10s %s\n' 'herdr' 'downloads the file and prints the steps'
  printf '  %-10s %s\n' 'vscode' 'installs the extension into code and cursor'
  printf '  %-10s %s\n' 'zed' 'installs the theme file'
  printf '  %-10s %s\n' 'jetbrains' 'downloads the file and prints the steps'
  printf '  %-10s %s\n' 'zellij' 'installs the theme file'
  printf '  %-10s %s\n' 'starship' 'downloads the file and prints the steps'
  printf '  %-10s %s\n' 'tmux' 'installs the theme file'
  printf '  %-10s %s\n' 'vim' 'installs the theme file'
  printf '  %-10s %s\n' 'xcode' 'installs the theme file'
  printf '  %-10s %s\n' 'micro' 'installs the theme file'
  printf '  %-10s %s\n' 'obsidian' 'needs BIGFACE_VAULT=/path/to/vault'
  printf '  %-10s %s\n' 'slack' 'prints the theme string'
  printf '  %-10s %s\n' 'raycast' 'opens the import link'
}

# get <remote path> <dest | ->   download from the site
get() {
  if [ "$2" = "-" ]; then curl -fsSL "$BASE/$1"; else curl -fsSL "$BASE/$1" -o "$2"; fi
}

# put <remote path> <dest file>
put() {
  dest="$2"
  if [ -n "$DRY" ]; then echo "  would write $dest"; return 0; fi
  mkdir -p "$(dirname "$dest")"
  part="$dest.part.$$"
  if get "$1" "$part"; then mv "$part" "$dest"; echo "  wrote $(tilde "$dest")"
  else rm -f "$part"; echo "  failed to download $1" >&2; return 1; fi
}

# Show $HOME as ~ so the output stays short.
tilde() {
  rest="$1"; out=""
  while :; do
    case "$rest" in
      *"$HOME"*) out="$out${rest%%"$HOME"*}~"; rest="${rest#*"$HOME"}" ;;
      *) out="$out$rest"; break ;;
    esac
  done
  printf '%s
' "$out"
}
note() { echo "  -> $(tilde "$1")"; }

detected() {
  case "$1" in
    pi) command -v pi >/dev/null 2>&1 || [ -d "$HOME/.pi/agent" ] ;;
    ghostty) [ -d "${BIGFACE_APPS:-/Applications}"/Ghostty.app ] || command -v ghostty >/dev/null 2>&1 || [ -d "$CFG/ghostty" ] ;;
    vscode) command -v code >/dev/null 2>&1 || command -v cursor >/dev/null 2>&1 ;;
    zed) [ -d "${BIGFACE_APPS:-/Applications}"/Zed.app ] || command -v zed >/dev/null 2>&1 || [ -d "$CFG/zed" ] ;;
    zellij) command -v zellij >/dev/null 2>&1 || [ -d "$CFG/zellij" ] ;;
    tmux) command -v tmux >/dev/null 2>&1 || [ -f "$HOME/.tmux.conf" ] || [ -d "$CFG/tmux" ] ;;
    vim) command -v vim >/dev/null 2>&1 || command -v nvim >/dev/null 2>&1 ;;
    xcode) [ -d "${BIGFACE_APPS:-/Applications}"/Xcode.app ] ;;
    micro) command -v micro >/dev/null 2>&1 || [ -d "$CFG/micro" ] ;;
    *) return 1 ;;
  esac
}

install_pi() {
  put 'themes/pi/bigface.json' "$HOME/.pi/agent/themes/bigface.json" || return 1
  note "Run \`pi --use-theme bigface\`, or pick it under /settings -> Theme."
}

install_ghostty() {
  put 'themes/ghostty/Bigface' "$CFG/ghostty/themes/Bigface" || return 1
  note "Add \`theme = Bigface\` to $CFG/ghostty/config and reload."
}

install_herdr() {
  put 'themes/herdr/theme.toml' "$CFG/bigface/herdr/theme.toml" || return 1
  note "herdr has no theme-file format: paste that file into $CFG/herdr/config.toml under your [theme] table, then run \`herdr config check\`."
}

install_vscode() {
  if [ -n "$DRY" ]; then
    echo "  would download downloads/bigface-theme-0.1.0.vsix and run: code/cursor --install-extension"
  else
    tmp="$(mktemp -d)"
    trap 'rm -rf "$tmp"' EXIT
    get 'downloads/bigface-theme-0.1.0.vsix' "$tmp/bigface-theme.vsix"
    found=""
    for editor in code cursor; do
      if command -v "$editor" >/dev/null 2>&1; then
        "$editor" --install-extension "$tmp/bigface-theme.vsix" >/dev/null && echo "  installed in $editor"
        found=1
      fi
    done
    if [ -z "$found" ]; then
      echo "  neither code nor cursor is on PATH; download $BASE/downloads/bigface-theme-0.1.0.vsix and use Extensions -> Install from VSIX." >&2
      return 1
    fi
  fi
  note "Pick Bigface under Preferences -> Color Theme."
}

install_zed() {
  put 'themes/zed/themes/bigface.json' "$CFG/zed/themes/bigface.json" || return 1
  note "Open the theme selector (cmd-k cmd-t) and choose Bigface."
}

install_jetbrains() {
  put 'themes/jetbrains/Bigface.xml' "$CFG/bigface/jetbrains/Bigface.xml" || return 1
  note "In your IDE: Settings -> Editor -> Color Scheme -> gear icon -> Import Scheme..., then choose that file."
}

install_zellij() {
  put 'themes/zellij/bigface.kdl' "$CFG/zellij/themes/bigface.kdl" || return 1
  note "Set \`theme \"bigface\"\` in $CFG/zellij/config.kdl."
}

install_starship() {
  put 'themes/starship/palette.toml' "$CFG/bigface/starship/palette.toml" || return 1
  note "Paste that file at the top of $CFG/starship.toml (the \`palette\` line must come before any table)."
}

install_tmux() {
  put 'themes/tmux/bigface.conf' "$CFG/tmux/bigface.conf" || return 1
  note "Add \`source-file $CFG/tmux/bigface.conf\` to ~/.tmux.conf, then \`tmux source ~/.tmux.conf\`."
}

install_vim() {
  put 'themes/vim/colors/bigface.vim' "$HOME/.vim/colors/bigface.vim" || return 1
  put 'themes/vim/colors/bigface.vim' "$CFG/nvim/colors/bigface.vim" || return 1
  note "Run \`:colorscheme bigface\`."
}

install_xcode() {
  put 'themes/xcode/Bigface.xccolortheme' "$HOME/Library/Developer/Xcode/UserData/FontAndColorThemes/Bigface.xccolortheme" || return 1
  note "Restart Xcode, then choose Bigface in Settings -> Themes."
}

install_micro() {
  put 'themes/micro/bigface.micro' "$CFG/micro/colorschemes/bigface.micro" || return 1
  note "In micro press ctrl-e and run \`set colorscheme bigface\` (needs COLORTERM=truecolor)."
}

install_obsidian() {
  if [ -z "${BIGFACE_VAULT:-}" ]; then
    echo "  obsidian: set BIGFACE_VAULT=/path/to/your/vault and run again." >&2
    return 1
  fi
  if [ ! -d "$BIGFACE_VAULT" ]; then
    echo "  obsidian: $BIGFACE_VAULT is not a directory." >&2
    return 1
  fi
  put 'themes/obsidian/Bigface/theme.css' "$BIGFACE_VAULT/.obsidian/themes/Bigface/theme.css" || return 1
  put 'themes/obsidian/Bigface/manifest.json' "$BIGFACE_VAULT/.obsidian/themes/Bigface/manifest.json" || return 1
  note "Select Bigface under Settings -> Appearance -> Themes. Needs BIGFACE_VAULT=/path/to/vault."
}

install_slack() {
  if [ -n "$DRY" ]; then echo "  would print slack theme"; else
    echo "  $(get 'themes/slack/theme.txt' -)"
  fi
  note "Paste it in Preferences -> Appearance -> Custom theme -> Import theme."
}

install_raycast() {
  url="$(get 'themes/raycast/theme.url' - | tr -d '\n')"
  if [ -n "$DRY" ]; then echo "  would open: $url"
  elif command -v open >/dev/null 2>&1; then open "$url"
  elif command -v xdg-open >/dev/null 2>&1; then xdg-open "$url"
  else echo "  open this link: $url"; fi
  note "Raycast asks to add the theme; accept it and pick Bigface in Settings -> Appearance."
}

valid() { case " $IDS " in *" $1 "*) return 0 ;; esac; return 1; }

targets=""
want_all=""
while [ $# -gt 0 ]; do
  case "$1" in
    -h|--help) usage; exit 0 ;;
    --list) list; exit 0 ;;
    -n|--dry-run) DRY=1 ;;
    all)
      want_all=1
      for a in $ALL; do if detected "$a"; then targets="$targets $a"; fi; done ;;
    -*) echo "unknown option: $1" >&2; usage >&2; exit 2 ;;
    *) targets="$targets $1" ;;
  esac
  shift
done

if [ -z "$targets" ]; then
  if [ -n "$want_all" ]; then echo "no supported apps detected; name one explicitly (see --list)."; exit 0; fi
  usage; echo; list; exit 0
fi

# Reject unknown names before writing anything.
for t in $targets; do
  if ! valid "$t"; then echo "unknown app: $t (try --list)" >&2; exit 2; fi
done

status=0
done_list=" "
for t in $targets; do
  case "$done_list" in *" $t "*) continue ;; esac
  done_list="$done_list$t "
  echo "$t"
  if "install_$t"; then :; else status=1; fi
done
exit $status
